"""The TypeScript types come from the API's own schema and are never out of date (FR-24, R-5)."""

import subprocess
import sys
from pathlib import Path

from farejador.api.routes import create_api
from farejador.web.typegen import generate_types

ROOT = Path(__file__).resolve().parent.parent.parent
TYPES = ROOT / "web" / "src" / "api" / "types.ts"


def test_the_committed_types_are_exactly_what_the_generator_produces() -> None:
    assert TYPES.read_text(encoding="utf-8") == generate_types(), (
        "web/src/api/types.ts is out of date: run `uv run python scripts/gen_api_types.py`"
    )


def test_the_generator_is_deterministic() -> None:
    assert generate_types() == generate_types()


def test_every_response_model_of_the_api_has_a_type() -> None:
    schemas = set(create_api("/nonexistent").openapi()["components"]["schemas"])
    generated = generate_types()
    for name in schemas - {"HTTPValidationError", "ValidationError"}:
        assert f"export interface {name} " in generated or f"export type {name} =" in generated, (
            name
        )


def test_the_generated_file_says_it_is_generated_and_where_from() -> None:
    first_lines = TYPES.read_text(encoding="utf-8").splitlines()[:2]
    assert "Generated by scripts/gen_api_types.py" in first_lines[0]
    assert "Do not edit by hand" in first_lines[1]


def test_nullable_and_optional_fields_keep_their_meaning() -> None:
    generated = generate_types()
    assert "readonly head_sha: string | null;" in generated
    assert "readonly tool_call_id?: string | null;" in generated  # optional with a default
    assert "readonly steps: readonly StepOut[];" in generated
    assert 'export type OutcomeFilter = "complete" | "partial" | "failed";' in generated


def test_the_script_writes_the_same_content(tmp_path: Path) -> None:
    before = TYPES.read_text(encoding="utf-8")
    subprocess.run(
        [sys.executable, str(ROOT / "scripts" / "gen_api_types.py")],
        check=True,
        capture_output=True,
    )
    assert TYPES.read_text(encoding="utf-8") == before
